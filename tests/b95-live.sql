begin;
do $test$
declare admin_id uuid; code text; original jsonb; state jsonb; edited jsonb; before jsonb; failed boolean; result jsonb;
begin
 select user_id into admin_id from public.support_admins limit 1;
 if admin_id is null then raise exception 'No admin fixture'; end if;
 if (select count(*) from public.course_editor_state)<>7 then raise exception 'Missing courses'; end if;
 if exists(select 1 from public.course_learning_content c cross join lateral jsonb_array_elements(c.payload->'lessons') l where c.course_code in ('NA-101','COMP-101') and (l->>'video' is null or l->>'video'='')) then raise exception 'Missing approved video'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',admin_id,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 foreach code in array array['PA-203','ID-101','MKT-201','PA-101','NA-101','COMP-101','ID-001'] loop
  state:=public.b95_editor_get(code); original:=state->'payload';
  if code='ID-001' then edited:=jsonb_set(original,'{items,0,sections,0,body,es}',to_jsonb((original#>>'{items,0,sections,0,body,es}')||' PRUEBA REVERTIDA'));
  elsif code='PA-203' then edited:=jsonb_set(original,'{lessons,0,text}',to_jsonb((original#>>'{lessons,0,text}')||' PRUEBA REVERTIDA'));
  else edited:=jsonb_set(original,'{lessons,0,title,es}',to_jsonb((original#>>'{lessons,0,title,es}')||' PRUEBA REVERTIDA')); end if;
  state:=public.b95_editor_save(code,edited,(state->>'draft_revision')::bigint,(state->>'published_revision')::bigint);
  before:=public.b95_course_published(code);
  if before->'payload' is distinct from original then raise exception 'Draft leaked into published'; end if;
  failed:=false;
  begin perform public.b95_editor_publish(code,(state->>'draft_revision')::bigint-1,(state->>'published_revision')::bigint); exception when serialization_failure then failed:=true; end;
  if not failed then raise exception 'CAS missing'; end if;
  state:=public.b95_editor_publish(code,(state->>'draft_revision')::bigint,(state->>'published_revision')::bigint);
  result:=public.b95_course_published(code);
  if result->'payload' is distinct from edited then raise exception 'Publication mismatch'; end if;
  state:=public.b95_editor_restore(code,1,(state->>'draft_revision')::bigint,(state->>'published_revision')::bigint);
  state:=public.b95_editor_publish(code,(state->>'draft_revision')::bigint,(state->>'published_revision')::bigint);
  result:=public.b95_course_published(code);
  if result->'payload' is distinct from original then raise exception 'Restore mismatch'; end if;
 end loop;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',gen_random_uuid(),'role','authenticated')::text,true);
 failed:=false;
 begin perform public.b95_editor_get('ID-001'); exception when insufficient_privilege then failed:=true; end;
 if not failed then raise exception 'Student allowed to edit'; end if;
 if public.b95_course_published('ID-001') is not null then raise exception 'Premium exposed'; end if;
 execute 'reset role';
 perform set_config('request.jwt.claims','{"role":"anon"}',true);
 execute 'set local role anon';
 result:=public.b95_course_published('ID-101');
 if result->'payload'->>'code'<>'ID-101' then raise exception 'Public source inaccessible'; end if;
 select payload into result from public.course_preview_content where course_code='ID-001';
 if jsonb_array_length(result->'samples')<>6 or jsonb_array_length(result->'syllabus')<>30 then raise exception 'Bad projection'; end if;
 if exists(select 1 from jsonb_array_elements(result->'syllabus') item where item ?| array['sections','practice','quiz','audio_text']) then raise exception 'Premium body leaked'; end if;
 failed:=false;
 begin perform public.b95_editor_get('ID-101'); exception when insufficient_privilege then failed:=true; end;
 if not failed then raise exception 'Anon edit allowed'; end if;
 execute 'reset role';
end;
$test$;
rollback;
select 'B95 live: seven save/publish/restore formats, CAS, premium and role checks PASS; all edits rolled back' as result;
