const assert=require('node:assert/strict');
const {TARGETS,REQUIREMENTS,evaluate,label}=require('../src/b58-launch-catalog.js');
assert.equal(TARGETS.length,5);
assert.notEqual(TARGETS[3].id,TARGETS[4].id);
const catalog={courses:[{code:'PA-203'},{code:'ID-101'},{code:'MKT-201'},{code:'EXTRA'}]};
let result=evaluate(catalog,{});
assert.equal(result.ready,0);
assert.equal(result.planned,5);
assert.equal(result.targets[3].status,'coming_soon');
assert(result.targets[3].missing.includes('catalog_entry'));
assert(result.targets[4].missing.includes('catalog_entry'));
const checks=Object.fromEntries(REQUIREMENTS.map(k=>[k,true]));
result=evaluate(catalog,{'PA-203':checks});
assert.equal(result.ready,1);
assert.equal(result.targets[0].status,'ready');
assert.equal(result.targets[1].status,'coming_soon');
assert.equal(label('coming_soon','en'),'Coming soon');
assert.equal(label('ready','es'),'Disponible');
assert.throws(()=>evaluate({courses:[{code:'PA-203'},{code:'PA-203'}]},{}));
assert.equal(evaluate({courses:TARGETS.map(x=>({code:x.id}))},Object.fromEntries(TARGETS.map(x=>[x.id,checks]))).allReady,true);
console.log('PASS: B58 launch gating (13 assertions)');
